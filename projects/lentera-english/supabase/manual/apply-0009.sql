-- 0009 (Rilis 3): CEFR-style level exams graded on the server, and
-- certificates with a public verification code.

-- Sections of a level exam (question pools and writing prompts) travel with the
-- exam row. The pools point at exam-only questions (stage 'exam').
alter table exams add column if not exists sections jsonb
  check (sections is null or jsonb_typeof(sections) = 'array');

-- One row per submitted attempt. The server draws the questions from the attempt
-- number, so the same attempt always shows the same questions and cannot be
-- re-rolled; the unique key stops a second submission of the same attempt.
create table level_exam_attempts (
  id bigint generated always as identity primary key,
  user_id uuid not null references profiles(id) on delete cascade,
  exam_id text not null,
  attempt int not null check (attempt >= 0),
  score int not null check (score between 0 and 100),
  passed boolean not null,
  sections jsonb not null default '[]',
  question_ids jsonb not null default '[]',
  writing text,
  submitted_at timestamptz not null default now(),
  unique (user_id, exam_id, attempt)
);
create index level_exam_attempts_user_idx on level_exam_attempts(user_id, exam_id, attempt desc);

-- A certificate is issued once per learner and level, on the first pass. The
-- code is generated by the server (crypto) and is all a verifier needs.
create table certificates (
  code text primary key check (code ~ '^[A-Z2-9]{10}$'),
  user_id uuid not null references profiles(id) on delete cascade,
  exam_id text not null,
  level_code text not null references cefr_levels(code),
  display_name text not null,
  score int not null check (score between 0 and 100),
  sections jsonb not null default '[]',
  attempt_id bigint references level_exam_attempts(id) on delete set null,
  issued_at timestamptz not null default now(),
  unique (user_id, exam_id)
);

alter table level_exam_attempts enable row level security;
alter table certificates enable row level security;
revoke all on table level_exam_attempts, certificates from anon, authenticated;

create or replace function level_exam_status(p_user uuid, p_exam text) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'attempts', (select count(*) from level_exam_attempts where user_id = p_user and exam_id = p_exam),
    'last_at', (select max(submitted_at) from level_exam_attempts where user_id = p_user and exam_id = p_exam),
    'last_passed', (select passed from level_exam_attempts where user_id = p_user and exam_id = p_exam order by attempt desc limit 1),
    'certificate', (select code from certificates where user_id = p_user and exam_id = p_exam));
$$;

-- Records a graded attempt and, on the first pass, the certificate.
create or replace function record_level_exam(p_user uuid, p_exam text, p_level text, p_attempt int, p_score int, p_passed boolean,
                                             p_sections jsonb, p_questions jsonb, p_writing text, p_code text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_code text;
begin
  if (select count(*) from level_exam_attempts where user_id = p_user and exam_id = p_exam) <> p_attempt then
    raise exception 'stale_attempt' using errcode = 'P0001';
  end if;
  insert into level_exam_attempts (user_id, exam_id, attempt, score, passed, sections, question_ids, writing)
  values (p_user, p_exam, p_attempt, p_score, p_passed, coalesce(p_sections, '[]'), coalesce(p_questions, '[]'), left(p_writing, 5000))
  returning id into v_id;
  select code into v_code from certificates where user_id = p_user and exam_id = p_exam;
  if p_passed and v_code is null then
    insert into certificates (code, user_id, exam_id, level_code, display_name, score, sections, attempt_id)
    values (p_code, p_user, p_exam, p_level, coalesce((select display_name from profiles where id = p_user), 'Pelajar'), p_score, coalesce(p_sections, '[]'), v_id);
    v_code := p_code;
  end if;
  return jsonb_build_object('id', v_id, 'certificate', v_code);
end $$;

-- Public verification: what the certificate says, never who owns the account.
create or replace function get_certificate(p_code text) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce((select jsonb_build_object('code', code, 'name', display_name, 'level', level_code, 'exam', exam_id, 'score', score, 'sections', sections, 'issued_at', issued_at)
                     from certificates where code = upper(btrim(p_code))), 'null'::jsonb);
$$;

create or replace function my_certificates(p_user uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('code', code, 'name', display_name, 'level', level_code, 'exam', exam_id, 'score', score, 'issued_at', issued_at) order by issued_at), '[]'::jsonb)
    from certificates where user_id = p_user;
$$;

create or replace function content_features() returns jsonb
language sql immutable as $$ select '["stories","content_notes","level_exams"]'::jsonb $$;

-- Lock every function down to the service role, as at the end of 0004/0005/0007/0008.
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.prokind = 'f' loop
    execute format('revoke execute on function %s from public, anon, authenticated', f.sig);
    execute format('grant execute on function %s to service_role', f.sig);
  end loop;
end $$;

